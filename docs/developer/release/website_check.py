"""Generate the web site from a release zip file, and check its internal links.

The web site, https://eisop.github.io/, is generated by the generator in
https://github.com/eisop/eisop.github.io from the GitHub releases.  Before the release is posted,
the generator runs on the release zip file, and every link from a generated page to a page or file
of the site must lead to a file the generator produced, or be one of the pages that only the full
site has, such as the list of releases, which checker/bin-devel/check-release-links.py lists as
SITE_SINGLETONS.  Every fragment must name an anchor of its page.  The Javadoc, generated by
javadoc, is linked to but not checked itself.
"""

from __future__ import annotations

import html.parser
import importlib.util
import urllib.parse
from typing import TYPE_CHECKING

from release_utils import clone_or_reset, delete_directory_if_exists
from release_vars import CHECKER_FRAMEWORK, TMP_DIR, execute_status

if TYPE_CHECKING:
    from pathlib import Path

WEBSITE_REPO = "https://github.com/eisop/eisop.github.io.git"
WEBSITE_CLONE = TMP_DIR / "eisop.github.io"
GENERATED_SITE = TMP_DIR / "website"
GENERATOR_CLASS = "io.github.eisop.website.EisopSiteGenerator"


class LinkParser(html.parser.HTMLParser):
    """Collects the links and the anchors of an HTML page."""

    def __init__(self) -> None:
        """Create a parser that has seen no links or anchors."""
        super().__init__()
        self.links: list[str] = []
        self.anchors: set[str] = set()

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        """Record the link and the anchors of a start tag."""
        for name, value in attrs:
            if value is None:
                continue
            if name == "id" or (tag == "a" and name == "name"):
                self.anchors.add(value)
            if (tag, name) in {("a", "href"), ("link", "href"), ("img", "src"), ("script", "src")}:
                self.links.append(value)


def parse(page: Path) -> LinkParser:
    """Return the links and anchors of the given page.

    Returns:
        the parser, with the page's links and anchors
    """
    parser = LinkParser()
    parser.feed(page.read_text(encoding="utf-8", errors="replace"))
    return parser


def site_singletons() -> set[str]:
    """Return the paths of the pages that only the full web site has.

    Returns:
        the SITE_SINGLETONS of checker/bin-devel/check-release-links.py
    """
    script = CHECKER_FRAMEWORK / "checker" / "bin-devel" / "check-release-links.py"
    spec = importlib.util.spec_from_file_location("check_release_links", script)
    if spec is None or spec.loader is None:
        msg = f"Cannot load {script}"
        raise ImportError(msg)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return set(module.SITE_SINGLETONS)


def link_problems(site: Path, singletons: set[str]) -> list[str]:
    """Check the internal links of the generated pages of the web site in the given directory.

    Args:
        site: the directory of the generated web site
        singletons: the paths of the pages that only the full web site has

    Returns:
        a description of each broken link
    """
    pages = [
        page for page in sorted(site.rglob("*.html")) if "api" not in page.relative_to(site).parts
    ]
    anchors: dict[Path, set[str]] = {}
    problems = []
    for page in pages:
        page_url = "/" + page.relative_to(site).as_posix()
        for link in parse(page).links:
            url = urllib.parse.urlsplit(urllib.parse.urljoin(page_url, link))
            if url.scheme or url.netloc or link.startswith(("mailto:", "javascript:")):
                continue
            target = site / urllib.parse.unquote(url.path).lstrip("/")
            if target.is_dir():
                target = target / "index.html"
            if not target.exists():
                if url.path not in singletons:
                    problems.append(f"{page_url}: {link} does not exist.")
                continue
            fragment = urllib.parse.unquote(url.fragment)
            if fragment and target.suffix == ".html" and "api" not in target.parts:
                if target not in anchors:
                    anchors[target] = parse(target).anchors
                if fragment not in anchors[target]:
                    problems.append(f"{page_url}: {link} names no anchor of its page.")
    return problems


def check_website(release_zip: Path) -> list[str]:
    """Generate the web site of the given release zip file, and check its internal links.

    The generated site is in GENERATED_SITE, for you to look at.

    Returns:
        a description of each problem, or an empty list if there is none
    """
    clone_or_reset(WEBSITE_REPO, WEBSITE_CLONE, shallow=True)
    if execute_status(["mvn", "-q", "-B", "package", "-DskipTests"], WEBSITE_CLONE) != 0:
        return [f"The web site generator in {WEBSITE_CLONE} does not build."]
    jar = WEBSITE_CLONE / "target" / "eisop.github.io-1.0-SNAPSHOT-jar-with-dependencies.jar"
    delete_directory_if_exists(GENERATED_SITE)
    GENERATED_SITE.mkdir(parents=True)
    generate = [
        "java",
        "-cp",
        str(jar),
        GENERATOR_CLASS,
        "--local-release",
        str(release_zip),
        "--only-latest",
    ]
    if execute_status(generate, GENERATED_SITE) != 0:
        return [f"The web site generator failed on {release_zip}."]
    return link_problems(GENERATED_SITE, site_singletons())
